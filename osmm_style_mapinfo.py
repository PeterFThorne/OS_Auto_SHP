def veg_scale(area):
    """Tile stretch factor, fitted to InterpOSe output (1.0 up to 10,000 m2)."""
    if area <= 10000:
        return 1.0
    return min(1 + 0.00016 * (area - 10000), math.sqrt(area / 3450.0))


