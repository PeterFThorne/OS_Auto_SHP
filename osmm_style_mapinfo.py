def _work(f):
    """Rough relative cost of styling one feature (1 = a typical line).
    Vegetation polygons dominate: symbol placement and clipping scale with
    vertex count x bounding-box area (fitted on real tiles)."""
    if f.cls != "TopographicArea" or "Natural Environment" not in f.xml:
        return 1.0
    rings = f.rings()
    if not rings:
        return 1.0
    xs = [q[0] for q in rings[0]]
    ys = [q[1] for q in rings[0]]
    nv = sum(len(r) for r in rings)
    bbox = (max(xs) - min(xs) + 10) * (max(ys) - min(ys) + 10)
    sc = veg_scale(_ring_area(rings[0]))
    return 1.0 + nv * bbox / (sc * sc) * 8.4e-4


def _with_progress(features, log, interval=0.5):
    """Pass features through, printing "styled NN%" at most every `interval`
    seconds (the GUI's progress bar follows these lines)."""
    import time
    features = list(features)
    weights = [_work(f) for f in features]
    total = sum(weights) or 1.0
    done, last = 0.0, time.time()
    for f, w in zip(features, weights):
        yield f
        done += w
        if time.time() - last >= interval:
            last = time.time()
            log(f"  styled {int(100 * done / total)}% ({len(features)} features)")
    log(f"  styled 100% ({len(features)} features)")


def style_site(source, output=None, make_tab=True, keep_mif=False, log=print):
    source = Path(source)
    gml = source / "site.gml.gz" if source.is_dir() else source
    if not gml.exists():
        sys.exit(f"Cannot find {gml}")
    out = Path(output) if output else gml.parent
    out.mkdir(parents=True, exist_ok=True)

    chunk = ""
    manifest = gml.parent / "manifest.json"
    if manifest.exists():
        files = json.loads(manifest.read_text()).get("source_files", [])
        orders = {os.path.basename(p.replace("\\", "/"))[:6] for p in files}
        chunk = orders.pop() if len(orders) == 1 else ""

    tables, report = build(_with_progress(read_features(gml), log), chunk)

    converter_name, convert = get_converter() if make_tab else (None, None)
    log(f"Writing tables to {out}")
    lines = []
    for name, table in tables.items():
        mif = table.write(out)
        status = "MIF"
        if convert:
            tab = out / f"{name}.tab"
            for ext in (".tab", ".dat", ".map", ".id", ".ind"):
                (out / f"{name}{ext}").unlink(missing_ok=True)
            differs = table.gdal_objects != table.objects
            src = table.write(out, for_gdal=True) if differs else mif
            ok = convert(src, tab) and tab.exists() and make_mapinfo85_safe(tab)
            if differs:
                src.unlink()
                src.with_suffix(".mid").unlink()
            if ok:
                status = "TAB"
                if not keep_mif:
                    mif.unlink()
                    (out / f"{name}.mid").unlink()
            else:
                status = "MIF (TAB conversion failed)"
                reason = getattr(convert, "last_error", "")
                if reason:
                    log(f"  Warning: {name} TAB conversion failed: {reason}")
        line = f"  {name:<10} {len(table.rows):>6} objects   {status}"
        log(line)
        lines.append(line)
        for legend, n in sorted(table.legends.items()):
            lines.append(f"      {n:>6}  {legend}")
    if make_tab and not convert:
        log("  Warning: GDAL not found: MIF/MID written only. In MapInfo use Table > Import.")
        for reason in _GDAL_ERRORS:
            log(f"    {reason}")
    elif convert:
        log(f"  TAB files made with {converter_name}")

    lines.append("")
    if report.unverified:
        lines.append("Classes not present in the InterpOSe sample (default style used):")
        for (table, what), n in sorted(report.unverified.items()):
            lines.append(f"  {table:<10} {n:>6}  {what}")
        log(f"  {len(report.unverified)} class(es) used a default style: see style_report.txt")
    else:
        lines.append("Every feature matched a defined style.")
    (out / "style_report.txt").write_text("\n".join(lines) + "\n")
    return tables, report


