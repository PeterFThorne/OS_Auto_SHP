def _inside(x, y, rings):
    inside = False
    for ring in rings:
        j = len(ring) - 1
        for i in range(len(ring)):
            xi, yi = ring[i]
            xj, yj = ring[j]
            if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
                inside = not inside
            j = i
    return inside


def _hash(i, j, k=0):
    h = (i * 73856093) ^ (j * 19349663) ^ (k * 83492791)
    h = (h ^ (h >> 13)) * 1274126177 & 0xFFFFFFFF
    return (h ^ (h >> 16)) / 0xFFFFFFFF


def _ring_area(ring):
    return abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(ring, ring[1:]))) / 2


def _fallback_stamp(term):
    """Big + small symbol pair, laid out like InterpOSe's tree stamps, for
    classes with no InterpOSe example (boulders, scree, marsh, coppice...)."""
    glyph, _scale, every = VEG_GLYPHS[term]
    scattered = every > 1
    big = place(GLYPHS[glyph], 1.4, 2.9, 0, 1.0)
    if scattered:
        return big
    return big + place(GLYPHS[glyph], 3.4, 0.7, 0, 0.45)


def _veg_stamps(legend, terms):
    """The stamp(s) to cycle through the tile positions."""
    if legend in VEG_STAMPS:
        return [VEG_STAMPS[legend]]
    stamps = []
    for t in VEG_GLYPHS:                       # fixed order
        if t not in terms:
            continue
        single = TREE_LEGENDS.get(frozenset([t]))
        stamps.append(VEG_STAMPS.get(single) or _fallback_stamp(t))
    return stamps


def _clip_parts(parts, rings, out):
    for part in parts:
        run = []
        for q in part:
            if _inside(q[0], q[1], rings):
                run.append(q)
            else:
                if len(run) >= 2:
                    out.append(run)
                run = []
        if len(run) >= 2:
            out.append(run)


MARSH_TERMS = {"Marsh", "Reeds", "Saltmarsh"}


def _marsh_water(legend, terms):
    """Blue water lines matching the marsh stamps (empty for other stamps)."""
    water = (place(GLYPHS["marshline"], 1.4, 2.9, 0, 1.0) +
             place(GLYPHS["marshline"], 3.4, 0.7, 0, 0.45))
    if legend in VEG_STAMPS:
        return [[]]
    return [water if t in MARSH_TERMS else [] for t in VEG_GLYPHS if t in terms]


def tree_pattern(rings, legend, terms, swap=None):
    """InterpOSe-style vegetation symbols for one polygon, cut at its edge.
    swap: draw these stamps instead (same positions), e.g. marsh water lines."""
    stamps = swap or _veg_stamps(legend, terms)
    if not stamps:
        return []
    xs = [q[0] for q in rings[0]]
    ys = [q[1] for q in rings[0]]
    x0, y0, x1, y1 = min(xs), min(ys), max(xs), max(ys)
    area = _ring_area(rings[0]) - sum(_ring_area(r) for r in rings[1:])
    s = veg_scale(area)
    tile = VEG_TILE * s
    positions = ORCHARD_POS if legend == "0386 Orchard" else VEG_TILE_POS
    out = []
    n = 0
    for tj in range(-1, int((y1 - y0) // tile) + 2):
        for ti in range(-1, int((x1 - x0) // tile) + 2):
            for px, py in positions:
                ax, ay = x0 + s * (px + VEG_TILE * ti), y0 + s * (py + VEG_TILE * tj)
                stamp = stamps[n % len(stamps)]
                n += 1
                if not stamp:
                    continue
                parts = [[(ax + u, ay + v) for u, v in part] for part in stamp]
                sx = [q[0] for part in parts for q in part]
                sy = [q[1] for part in parts for q in part]
                if max(sx) < x0 or min(sx) > x1 or max(sy) < y0 or min(sy) > y1:
                    continue
                corners = [(min(sx), min(sy)), (max(sx), min(sy)), (min(sx), max(sy)),
                           (max(sx), max(sy)), ((min(sx) + max(sx)) / 2, (min(sy) + max(sy)) / 2)]
                hits = [_inside(cx, cy, rings) for cx, cy in corners]
                if all(hits):
                    out.extend(parts)
                else:
                    _clip_parts(parts, rings, out)
    return out


def cliff_hatch(rings, step=None):
    """Diagonal hatching (135 deg) through a cliff polygon, on lines where
    x + y is a multiple of `step`, so neighbouring cliffs line up."""
    step = step or CLIFF_HATCH
    sums = [x + y for ring in rings for x, y in ring]
    out = []
    for k in range(int(min(sums) // step), int(max(sums) // step) + 2):
        c = k * step
        hits = []
        for ring in rings:
            for (x1, y1), (x2, y2) in zip(ring, ring[1:]):
                f1, f2 = x1 + y1 - c, x2 + y2 - c
                if (f1 > 0) != (f2 > 0):
                    hits.append(x1 + (x2 - x1) * f1 / (f1 - f2))
        hits.sort()
        for a, b in zip(hits[0::2], hits[1::2]):
            if b - a > 0.05:
                out.append([(round(a, 2), round(c - a, 2)), (round(b, 2), round(c - b, 2))])
    return out


